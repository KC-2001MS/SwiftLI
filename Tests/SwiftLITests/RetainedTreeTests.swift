//  A rendering session keeps a `RetainedTree` between frames: child views'
//  `@State` survives the re-evaluation of their parent's body, and subtrees
//  whose lowered nodes did not change are handed the previous frame's node
//  (so their measurements are reused). These tests pin down the state
//  semantics and that reuse never changes what a frame shows.

import Testing
import Foundation
import ArgumentParser
@_spi(RenderingInternals) @testable import SwiftLI

/// Hands a view's `$state` binding out to the test, so the test can mutate
/// state that lives inside a view it cannot otherwise reach.
private final class BindingProbe<Value: Sendable>: @unchecked Sendable {
    var binding: Binding<Value>?
    func record(_ binding: Binding<Value>) { self.binding = binding }
}

/// A child view with `@State` of its own. Every frame creates a fresh
/// instance; only the retained tree makes `count` persist between them.
private struct Counter: View {
    @State private var count = 0
    let probe: BindingProbe<Int>

    // Spelled out because older compilers (e.g. Swift 6.2) count the private
    // state's storage in the memberwise initializer, which makes it private.
    init(probe: BindingProbe<Int>) {
        self.probe = probe
    }

    var body: some View {
        let _ = probe.record($count)
        Text("count=\(count)")
    }
}

/// Renders `view` as one frame of a session retaining `tree`, returning the
/// frame's lines.
private func frame(_ view: any View, retaining tree: RetainedTree?) -> [String] {
    RenderPassContext.withPass(retaining: tree) {
        NodeLayout.frame(of: view.lowered(at: 0)).lines
    }
}

@Suite("Retained tree")
struct RetainedTreeTests {

    @Test("A child view's @State persists across the frames of a session")
    func childStatePersists() {
        let tree = RetainedTree()
        let probe = BindingProbe<Int>()

        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=0"])
        probe.binding?.wrappedValue = 5
        // A new Counter instance — as a re-evaluated parent body would make —
        // is handed the same storage.
        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=5"])
        probe.binding?.wrappedValue += 1
        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=6"])
    }

    @Test("Without a session, each render starts from the initial value")
    func noSessionNoPersistence() {
        let probe = BindingProbe<Int>()
        #expect(frame(Counter(probe: probe), retaining: nil) == ["count=0"])
        probe.binding?.wrappedValue = 5
        #expect(frame(Counter(probe: probe), retaining: nil) == ["count=0"])
    }

    @Test("State is dropped with the view that owned it")
    func stateDropsWithView() {
        let tree = RetainedTree()
        let probe = BindingProbe<Int>()

        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=0"])
        probe.binding?.wrappedValue = 5
        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=5"])
        // A frame without the counter: its identity leaves the tree.
        #expect(frame(Text("gone"), retaining: tree) == ["gone"])
        #expect(frame(Counter(probe: probe), retaining: tree) == ["count=0"])
    }

    @Test("The two branches of an `if` have distinct identities")
    func conditionalBranchesAreDistinct() {
        struct Switcher: View {
            let flag: Bool
            let probe: BindingProbe<Int>
            var body: some View {
                if flag {
                    Counter(probe: probe)
                } else {
                    Counter(probe: probe)
                }
            }
        }
        let tree = RetainedTree()
        let probe = BindingProbe<Int>()

        #expect(frame(Switcher(flag: true, probe: probe), retaining: tree) == ["count=0"])
        probe.binding?.wrappedValue = 3
        #expect(frame(Switcher(flag: true, probe: probe), retaining: tree) == ["count=3"])
        // The other branch is a different view, with state of its own.
        #expect(frame(Switcher(flag: false, probe: probe), retaining: tree) == ["count=0"])
    }

    @Test("Sibling views keep separate state")
    func siblingsAreSeparate() {
        let tree = RetainedTree()
        let a = BindingProbe<Int>()
        let b = BindingProbe<Int>()
        let view = VStack {
            Counter(probe: a)
            Counter(probe: b)
        }

        #expect(frame(view, retaining: tree) == ["count=0", "count=0"])
        a.binding?.wrappedValue = 1
        b.binding?.wrappedValue = 2
        #expect(frame(view, retaining: tree) == ["count=1", "count=2"])
    }

    @Test("Rows generated by ForEach keep their own state")
    func forEachRowsKeepState() {
        let tree = RetainedTree()
        let probes = (0..<3).map { _ in BindingProbe<Int>() }
        let view = VStack {
            ForEach(0..<3) { i in Counter(probe: probes[i]) }
        }

        #expect(frame(view, retaining: tree) == ["count=0", "count=0", "count=0"])
        probes[1].binding?.wrappedValue = 7
        #expect(frame(view, retaining: tree) == ["count=0", "count=7", "count=0"])
    }

    @Test("An unchanged subtree is handed the previous frame's node storage")
    func unchangedSubtreeReusesStorage() {
        let tree = RetainedTree()
        let view = VStack {
            ForEach(0..<50) { i in Text("Row \(i)") }
        }

        func lower() -> RenderNode {
            RenderPassContext.withPass(retaining: tree) {
                let node = view.lowered(at: 0)
                _ = NodeLayout.frame(of: node)
                return node
            }
        }
        guard case .vstack(_, _, let first) = lower(), case .vstack(_, _, let second) = lower() else {
            Issue.record("expected vstack nodes")
            return
        }
        #expect(RenderNode.sameStorage(first, second))
    }

    @Test("Reuse never changes what a frame shows")
    func reuseMatchesFreshRender() {
        let tree = RetainedTree()
        var rng = SystemRandomNumberGenerator()

        func content(selected: Int, label: String) -> any View {
            VStack(alignment: .leading, spacing: 0) {
                Text(label).bold()
                ForEach(0..<40) { i in
                    HStack(spacing: 1) {
                        Text(i == selected ? ">" : " ")
                        Text("Row \(i)")
                            .foregroundStyle(i % 3 == 0 ? .cyan : .primary)
                    }
                }
                Divider()
                // A controlled viewport: its offset comes from the test, not
                // from the shared focus coordinator other suites may touch.
                ScrollView(height: 6, offset: selected % 24, focused: selected % 2 == 0, content: [
                    ForEach(0..<30) { i in Text("Line \(i) \(label)") },
                ])
            }
        }

        for step in 0..<40 {
            let selected = Int.random(in: 0..<40, using: &rng)
            let label = step % 4 == 0 ? "stable" : "step \(step)"
            let view = content(selected: selected, label: label)
            let retained = frame(view, retaining: tree)
            let fresh = frame(view, retaining: nil)
            if retained != fresh {
                let mismatch = zip(retained, fresh).enumerated().first { $0.element.0 != $0.element.1 }
                Issue.record("frame \(step) selected=\(selected) label=\(label) counts \(retained.count)/\(fresh.count) first mismatch at \(mismatch.map { "\($0.offset): \($0.element.0.debugDescription) vs \($0.element.1.debugDescription)" } ?? "tail")")
            }
        }
    }

    @Test("@State inside an ArgumentParser command still decodes and keeps its initial value")
    func commandStateDecodes() throws {
        struct Fixture: InlineCommand {
            @Option var name = "default"
            @State var count = 3
            @State private var hidden: String? = nil

            var body: some View {
                Text("\(name) \(count) \(hidden ?? "-")")
            }
        }

        let parsed = try Fixture.parse(["--name", "given"])
        #expect(parsed.name == "given")
        #expect(parsed.count == 3)
        #expect(parsed.$count.wrappedValue == 3)
        parsed.count += 1
        #expect(parsed.count == 4)
        #expect(parsed.body.renderString() == "given 4 -")
    }
}
